import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'i18n', 'exercise-names.ts');
const outputPath = path.join(
  root,
  'android',
  'app',
  'src',
  'main',
  'java',
  'org',
  'sharteman',
  'gymcoach',
  'ui',
  'localization',
  'ExerciseNamesRu.generated.kt',
);

const source = await readFile(sourcePath, 'utf8');
const marker = 'ru: {';
const markerIndex = source.indexOf(marker);
if (markerIndex < 0) throw new Error(`Could not find ${marker} in ${sourcePath}`);

const objectStart = source.indexOf('{', markerIndex);
const objectEnd = findMatchingBrace(source, objectStart);
const objectLiteral = source.slice(objectStart, objectEnd + 1);
const dictionary = Function(`"use strict"; return (${objectLiteral});`)();

const entries = Object.entries(dictionary)
  .map(([name, translation]) => [name.trim().toLocaleLowerCase('en-US'), translation])
  .sort(([left], [right]) => left.localeCompare(right, 'en-US'));

const lines = [
  '// Generated by scripts/generate-android-exercise-names.mjs. Do not edit manually.',
  'package org.sharteman.gymcoach.ui.localization',
  '',
  'internal val russianExerciseNames: Map<String, String> = mapOf(',
  ...entries.map(([name, translation]) => `    ${kotlinString(name)} to ${kotlinString(translation)},`),
  ')',
  '',
];
const next = lines.join('\n');
const current = await readFile(outputPath, 'utf8').catch(() => null);
if (current !== next) await writeFile(outputPath, next, 'utf8');

function kotlinString(value) {
  return JSON.stringify(value).replaceAll('$', '\\$');
}

function findMatchingBrace(text, start) {
  let depth = 0;
  let quote = null;
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let index = start; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];
    if (lineComment) {
      if (char === '\n') lineComment = false;
      continue;
    }
    if (blockComment) {
      if (char === '*' && next === '/') {
        blockComment = false;
        index += 1;
      }
      continue;
    }
    if (quote) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === '/' && next === '/') {
      lineComment = true;
      index += 1;
      continue;
    }
    if (char === '/' && next === '*') {
      blockComment = true;
      index += 1;
      continue;
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char;
      continue;
    }
    if (char === '{') depth += 1;
    if (char === '}') {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  throw new Error(`Unclosed object literal in ${sourcePath}`);
}
